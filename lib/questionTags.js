// =============================================================
// 손들기 태그 — '무엇 때문에 손을 들었나'
// -------------------------------------------------------------
// 손바닥 하나로는 '질문이 있다'까지만 전해집니다. 교사는 목록에서 이름만
// 보고 다가가야 했고, 학생은 말로 다시 설명해야 했습니다. 태그 하나와
// 짧은 메모를 함께 보내면 교사가 가기 전에 무엇인지 알 수 있습니다.
//
// 셋으로 못 박아 둔 이유: 고르는 데 시간이 들면 손을 드는 일 자체가
// 부담이 됩니다. 수업 중에 실제로 생기는 갈래가 이 셋입니다.
//
// **저장에는 key만** 들어갑니다(문자열 몇 글자). 이름과 색은 여기서
// 가져다 쓰므로, 나중에 말을 다듬어도 지난 기록이 따라옵니다.
// =============================================================
export const QUESTION_TAGS = [
  { key: "ask", label: "선생님, 질문이요!", emoji: "🙋" },
  { key: "idea", label: "이런 기능 어때요?", emoji: "💡" },
  { key: "bug", label: "으악! 오류 발견!", emoji: "🐞" },
];

export const QUESTION_TAG_KEYS = QUESTION_TAGS.map((t) => t.key);

// 저장된 key → 태그. 모르는 값(옛 기록·손댄 값)이면 null입니다 —
// 부르는 쪽이 '태그 없음'으로 다루면 됩니다.
export function questionTagOf(key) {
  return QUESTION_TAGS.find((t) => t.key === key) ?? null;
}

// 메모 길이 — 규칙(firestore.rules)과 같은 값이어야 합니다.
export const QUESTION_NOTE_MAX = 1000;
