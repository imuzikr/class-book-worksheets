// 구글은 자체 정책으로 이런 임베디드 웹뷰 안에서의 OAuth 로그인을
// 막습니다(피싱 방지 목적, disallowed_useragent). 그 결과 구글 로그인
// 팝업이 열리자마자 구글이 자체적으로 거부 화면을 띄우거나 팝업이
// 곧바로 닫혀, 우리 쪽 에러 코드만 봐서는 원인을 알 수 없습니다.
// 반면 이메일/비밀번호 가입은 이 제한과 무관해 같은 계정이라도 정상
// 동작합니다 — "구글로는 안 되는데 이메일로는 된다"는 신고의 가장
// 흔한 원인입니다. 사용자 에이전트 판별은 완벽할 수 없으므로, 오탐이
// 있어도 안내만 하고 로그인 자체를 막지는 않습니다.
// =============================================================
const IN_APP_PATTERNS = [
  /KAKAOTALK/i,
  /NAVER\(/i, // 네이버 앱 내 브라우저(독립 브라우저인 웨일과는 다름)
  /Instagram/i,
  /FBAN|FBAV/i, // 페이스북·메신저
  /Line\//i,
  /wv\)/i, // 안드로이드 웹뷰 표기
];

export function isInAppBrowser() {
  if (typeof navigator === "undefined") return false;
  const ua = navigator.userAgent || "";
  return IN_APP_PATTERNS.some((re) => re.test(ua));
}
