// =============================================================
// 실행 결과 → 카드에 남길 글자
// -------------------------------------------------------------
// 코드 셀의 결과(lib/pyCells.js)가 이 글자입니다 — 나중에 카드를 펴 봤을 때
// '무엇을 짰고 무엇이 나왔나'가 한눈에 남아야 복습이 됩니다. HTML로 적는
// 것(이스케이프 · `pre.py-result`)은 lib/pyCells.js의 serializeCells 한 곳입니다.
// 예전에는 여기의 pyResultHtml이 '실행 결과' 이름줄 + 결과 블록을 짜서 칸에
// 덧붙였는데, 셀이 결과를 제 것으로 들면서 그 길이 없어졌습니다.
// =============================================================

// 실행기의 출력 줄({type, text})을 사람이 읽는 한 덩이로.
// 안내 줄('── 실행 완료 ──' 등)은 빼고 실제 출력·오류만 남깁니다 —
// 카드에 남길 것은 프로그램이 낸 말이지 실행기가 낸 말이 아닙니다.
//
// **줄바꿈으로 잇습니다.** Pyodide는 출력을 한 줄씩, 끝의 줄바꿈을 **뗀 채**
// 넘깁니다(0.26.4 실측: print 셋 → "skan" · "테스트" · "테스트"). 화면은 줄마다
// `display: block`이라 멀쩡해 보이지만, 빈 글자로 이으면 붙인 결과가
// 'skan테스트테스트' 한 줄로 뭉개집니다.
// input()이 찍은 '입력한 값'은 여기서도 그대로 남깁니다 — 카드에는 색을 담을
// 수 없지만, 빼면 무엇을 넣어 나온 결과인지 알 수 없습니다.
export function outputTextOf(lines) {
  return (lines ?? [])
    .filter((l) => l?.type === "out" || l?.type === "err" || l?.type === "result")
    .map((l) => String(l.text ?? ""))
    .join("\n")
    .replace(/\s+$/, "");
}
