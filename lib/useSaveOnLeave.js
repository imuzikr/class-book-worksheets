"use client";
// =============================================================
// 화면을 떠날 때 아직 못 보낸 글을 곧바로 저장합니다 — 자동 저장하는 독서 활동 화면들이 함께 씁니다.
// -------------------------------------------------------------
// 자동 저장은 타자가 멈춘 뒤 잠깐(0.9초쯤) 모았다 보내는데, 그 타이머는 화면이 사라질 때 함께 걷힙니다. 그래서 글을
// 쓰자마자 다른 화면으로 가면(← 활동 목록 · 선생님의 '모두 이동'으로 책 광장에 불려 갈 때) 마지막 한두 낱말이 저장되지
// 않은 채 사라졌습니다. 떠나는 순간 한 번 더 보냅니다.
//
//   save()  아직 못 보낸 것이 있으면 지금 값을 저장하는 함수 — 보낼 것이 있는지는 부르는 쪽이 가립니다(타이머가 걸려
//           있는가). 화면이 이미 사라진 뒤라 실패를 알릴 자리가 없으므로, 부르는 쪽이 실패를 삼킵니다.
//
// 렌더마다 새 함수를 받아 최신 값을 봅니다(효과는 한 번만 겁니다 — 사라질 때만 부름).
// 개발 모드의 '마운트 직후 정리' 한 번은 보낼 것이 없어 아무 일도 하지 않습니다.
// =============================================================
import { useEffect, useRef } from "react";

export function useSaveOnLeave(save) {
  const latest = useRef(save);
  latest.current = save;
  useEffect(() => () => { latest.current?.(); }, []);
}
